type Design = DtDiagram & { data: DesignData };
const asDesign = (d: DtDiagram) => d as unknown as Design;
const newKey = () => `g-${Date.now().toString(36)}`;
const SIZE: Record<DesignData['device'], { w: number; h: number; label: string }> = {
  phone: { w: 390, h: 844, label: 'Phone' }, tablet: { w: 834, h: 1112, label: 'Tablet' }, desktop: { w: 1440, h: 900, label: 'Desktop' },
};
const STATE: Record<DesignData['state'], string> = { draft: 'Draft', review: 'In review', approved: 'Approved' };
/** A Figma link as Figma's own embed (read-only; the person's Figma sign-in decides what it shows). */
export const figmaEmbed = (url: string) => `https://www.figma.com/embed?embed_host=projecttracker&url=${encodeURIComponent(url)}`;
/** A generated screen inside a frame that can run nothing and load nothing. */
const shell = (html: string) => `<!doctype html><html><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; img-src data:; font-src data:"><style>html,body{margin:0;font-family:system-ui,-apple-system,sans-serif}</style></head><body>${html}</body></html>`;

/** One design drawn at its real size and scaled to fit `width`. */
function Screen({ d, width, live = false }: { d: DesignData; width: number; live?: boolean }) {
  const size = SIZE[d.device] ?? SIZE.phone;
  const scale = width / size.w;
  const [img, setImg] = useState<string | null>(null);
  useEffect(() => {
    if (d.source !== 'image' || !d.fileId) return;
    const ctl = new AbortController();
    void attachmentApi.inlineBlob(d.fileId, ctl.signal).then(setImg).catch(() => setImg(null));
    return () => ctl.abort();
  }, [d.source, d.fileId]);
  const box: CSSProperties = { width, height: Math.round(size.h * scale) };
  if (d.source === 'figma' && d.url) {
    return live
      ? <iframe className="dz-figma" title="Figma design" src={figmaEmbed(d.url)} style={box} allowFullScreen referrerPolicy="no-referrer" />
      : <div className="dz-figma-card" style={box}><Icon name="layers" size={26} /><b>Figma</b><span>{d.url.replace(/^https:\/\/(www\.)?figma\.com\//, '').split('/')[1]?.slice(0, 18)}</span><small>Opens live</small></div>;
  }
  if (d.source === 'image') return <div className="dz-img" style={box}>{img ? <img src={img} alt="" /> : <span className="dz-shim" />}</div>;
  return (
    <div className="dz-ai" style={box}>
      <iframe title="Generated screen" sandbox="" srcDoc={shell(d.html ?? '')} style={{ width: size.w, height: size.h, transform: `scale(${scale})` }} tabIndex={-1} />
    </div>
  );
}

/**
 * A project's designs, kept in its documentation: Figma files and frames (shown with Figma's embed, always the current version, read-only),
 * pictures uploaded to the project, and screens generated by AI from a sentence. Grouped by flow, each with a state (draft, in review,
 * approved) and a note; opened full size one at a time with ← →. Saved beside the project's diagrams.
 */
export function Designs({ projectId, projectName }: { projectId: string | null; projectName: string }) {
  const wid = useWorkspaceId();
  const q = useWsQuery(['documents', 'doctracker', 'architecture', projectId ?? 'general'], () => docTrackerApi.architecture(projectId));
  const all = q.data?.diagrams ?? [];
  const designs = useMemo(() => all.filter((d) => d.kind === 'design').map(asDesign), [all]);
  const [adding, setAdding] = useState(false);
  const [open, setOpen] = useState<number | null>(null);
  const [group, setGroup] = useState<string>('All');
  const save = useMutation({
    mutationFn: (next: Design[]) => docTrackerApi.saveArchitecture(projectId, { diagrams: [...all.filter((d) => d.kind !== 'design'), ...(next as unknown as DtDiagram[])], notes: q.data?.notes ?? null }),
    onSuccess: () => { void q.refetch(); invalidateWorkspace(wid, 'documents'); },
    onError: (e) => toast(e instanceof ApiError ? e.message : 'Could not save the design.', 'error'),
  });
  if (q.isError) return <ErrorState error={q.error} retry={() => void q.refetch()} />;
  if (q.isLoading) return <PageLoader />;
  const canEdit = !!q.data?.canEdit;
  const groups = ['All', ...Array.from(new Set(designs.map((d) => d.data.group).filter((g): g is string => !!g)))];
  const shown = designs.filter((d) => group === 'All' || d.data.group === group);
  const counts = { figma: designs.filter((d) => d.data.source === 'figma').length, ai: designs.filter((d) => d.data.source === 'ai').length, approved: designs.filter((d) => d.data.state === 'approved').length };
  const put = (next: Design[], ok: string) => save.mutate(next, { onSuccess: () => toast(ok, 'success') });

  return (
    <div className="dz" data-testid="designs">
      <header className="dx-hero-p dx-reveal">
        <p className="dx-eyebrow">Designs</p>
        <h1 className="dx-title">What {projectName} looks like</h1>
        <p className="dx-lede">{designs.length ? `${plural(designs.length, 'screen')} · ${counts.figma} from Figma · ${counts.ai} drafted with AI · ${counts.approved} approved${q.data?.updatedAt ? ` · updated ${timeAgo(q.data.updatedAt)}` : ''}.` : 'Keep the screens beside the docs: link Figma, upload pictures, or describe a screen and let AI draft it.'}</p>
        {canEdit && <div className="dx-row"><button type="button" className="dx-btn tint" onClick={() => setAdding(true)}><Icon name="plus" size={13} /> Add a design</button></div>}
      </header>
      {groups.length > 2 && (
        <div className="dz-groups" role="tablist" aria-label="Flows">
          {groups.map((g) => <button key={g} type="button" role="tab" aria-selected={group === g} className={group === g ? 'on' : ''} onClick={() => setGroup(g)}>{g}</button>)}
        </div>
      )}
      {designs.length === 0 ? (
        <div className="dx-arch-blank dz-blank">
          <Icon name="layers" size={28} />
          <b>No designs yet</b>
          <p>Paste a Figma link to show its frames here, upload a screenshot, or describe a screen — “A payment success screen with the amount and a Done button”.</p>
          {canEdit && <button type="button" className="dx-btn pri" onClick={() => setAdding(true)}>Add a design</button>}
        </div>
      ) : (
        <ul className="dz-grid">
          {shown.map((d, n) => (
            <li key={d.key} style={{ '--i': n } as CSSProperties}>
              <button type="button" className="dz-card" onClick={() => setOpen(designs.indexOf(d))} aria-label={`Open ${d.title}`}>
                <Screen d={d.data} width={d.data.device === 'phone' ? 200 : 280} />
              </button>
              <div className="dz-cap"><b>{d.title}</b><span className={`dz-state s-${d.data.state}`}>{STATE[d.data.state]}</span></div>
              <small className="dz-src">{d.data.source === 'figma' ? 'Figma' : d.data.source === 'ai' ? 'AI draft' : 'Picture'}{d.data.group ? ` · ${d.data.group}` : ''}</small>
            </li>
          ))}
        </ul>
      )}
      {adding && <AddDesign projectId={projectId} groups={groups.slice(1)} onClose={() => setAdding(false)} onAdd={(d) => { setAdding(false); put([...designs, d], `${d.title} added.`); }} />}
      {open !== null && designs[open] && (
        <Viewer designs={designs} index={open} canEdit={canEdit} onIndex={setOpen} onClose={() => setOpen(null)}
          onChange={(d) => put(designs.map((x) => (x.key === d.key ? d : x)), 'Saved.')}
          onDelete={async (d) => { if (await confirmDialog({ title: `Remove “${d.title}”?`, message: 'It is taken out of this project’s designs. A Figma file itself is not changed.', confirmText: 'Remove' })) { setOpen(null); put(designs.filter((x) => x.key !== d.key), 'Removed.'); } }} />
      )}
    </div>
  );
}

/** Add a design: a Figma link, a picture, or a screen described to AI (previewed before it is kept). */
function AddDesign({ projectId, groups, onClose, onAdd }: { projectId: string | null; groups: string[]; onClose: () => void; onAdd: (d: Design) => void }) {
  const [how, setHow] = useState<'figma' | 'ai' | 'image'>('figma');
  const [title, setTitle] = useState('');
  const [group, setGroup] = useState('');
  const [device, setDevice] = useState<DesignData['device']>('phone');
  const [url, setUrl] = useState('');
  const [prompt, setPrompt] = useState('');
  const [draft, setDraft] = useState<{ html: string; title: string } | null>(null);
  const [busy, setBusy] = useState(false);
  const file = useRef<HTMLInputElement>(null);
  const figmaOk = /^https:\/\/(www\.)?figma\.com\/(file|design|proto|board)\/[A-Za-z0-9]{10,64}/.test(url.trim());
  const base = (data: DesignData, t: string): Design => ({ key: newKey(), title: (title.trim() || t).slice(0, 120), kind: 'design', data: { ...data, group: group.trim() || undefined } } as unknown as Design);
  const generate = async () => {
    if (!prompt.trim()) return;
    setBusy(true);
    try { const r = await docTrackerApi.aiDesign(prompt.trim(), device); setDraft({ html: r.html, title: r.title }); }
    catch (e) { toast(e instanceof ApiError ? e.message : 'The assistant could not draw that screen.', 'error'); }
    finally { setBusy(false); }
  };
  const upload = async (f: File) => {
    if (!projectId) { toast('Pictures are kept with a project. Open a project’s documentation to upload one.', 'info'); return; }
    setBusy(true);
    try { const a = await attachmentApi.upload(projectId, f); onAdd(base({ source: 'image', fileId: a.id, device, state: 'draft' }, f.name.replace(/\.[^.]+$/, ''))); }
    catch (e) { toast(e instanceof ApiError ? e.message : 'Could not upload the picture.', 'error'); }
    finally { setBusy(false); }
  };
  return createPortal(
    <div className="dz-sheet-back" onClick={(e) => { if (e.target === e.currentTarget) onClose(); }}>
      <section className="dz-sheet" role="dialog" aria-modal="true" aria-label="Add a design">
        <header><h2>Add a design</h2><button type="button" className="dx-ibtn" aria-label="Close" onClick={onClose}><Icon name="close" size={14} /></button></header>
        <div className="dz-how" role="tablist" aria-label="How">
          {([['figma', 'Figma link'], ['ai', 'Describe it'], ['image', 'Upload a picture']] as const).map(([k, l]) => <button key={k} type="button" role="tab" aria-selected={how === k} className={how === k ? 'on' : ''} onClick={() => setHow(k)}>{l}</button>)}
        </div>
        <div className="dz-fields">
          <label>Name<input value={title} onChange={(e) => setTitle(e.target.value)} maxLength={120} placeholder="Payment success" /></label>
          <label>Flow<input value={group} onChange={(e) => setGroup(e.target.value)} maxLength={80} list="dz-groups" placeholder="Onboarding" /><datalist id="dz-groups">{groups.map((g) => <option key={g} value={g} />)}</datalist></label>
          <label>Device<select value={device} onChange={(e) => setDevice(e.target.value as DesignData['device'])}>{(Object.keys(SIZE) as DesignData['device'][]).map((k) => <option key={k} value={k}>{SIZE[k].label}</option>)}</select></label>
        </div>
        {how === 'figma' && (<>
          <label className="dz-wide">Figma link<input value={url} onChange={(e) => setUrl(e.target.value)} placeholder="https://www.figma.com/design/…/Onboarding?node-id=12-4" /></label>
          <p className="dz-hint">Link a whole file or one frame (Copy link to selection in Figma). It shows the current version, read-only, to people who can open it in Figma.</p>
          {figmaOk && <div className="dz-preview"><Screen d={{ source: 'figma', url: url.trim(), device, state: 'draft' }} width={device === 'phone' ? 260 : 420} live /></div>}
          <footer><button type="button" className="dx-btn pri" disabled={!figmaOk} onClick={() => onAdd(base({ source: 'figma', url: url.trim(), device, state: 'draft' }, 'Figma design'))}>Add</button></footer>
        </>)}
        {how === 'ai' && (<>
          <label className="dz-wide">Describe the screen<textarea rows={3} value={prompt} onChange={(e) => setPrompt(e.target.value)} maxLength={1500} placeholder="A payment success screen with the amount, the masked account and a Done button" /></label>
          {draft && <div className="dz-preview dz-rise"><Screen d={{ source: 'ai', html: draft.html, device, state: 'draft' }} width={device === 'phone' ? 260 : 460} /></div>}
          <footer>
            <button type="button" className="dx-btn" disabled={busy || !prompt.trim()} onClick={() => void generate()}>{busy ? 'Drawing…' : draft ? 'Try again' : 'Generate'}</button>
            {draft && <button type="button" className="dx-btn pri" onClick={() => onAdd(base({ source: 'ai', html: draft.html, prompt: prompt.trim(), device, state: 'draft' }, draft.title))}>Keep it</button>}
          </footer>
        </>)}
        {how === 'image' && (<>
          <p className="dz-hint">PNG, JPG or WebP — a screenshot or an export from your design tool. It is kept with the project’s files.</p>
          <input ref={file} type="file" accept="image/png,image/jpeg,image/webp" hidden onChange={(e) => { const f = e.target.files?.[0]; if (f) void upload(f); e.target.value = ''; }} />
          <footer><button type="button" className="dx-btn pri" disabled={busy} onClick={() => file.current?.click()}>{busy ? 'Uploading…' : 'Choose a picture'}</button></footer>
        </>)}
      </section>
    </div>, document.body);
}

/** One design full size: Figma live, ← → between designs, its state and note, Open in Figma, Remove. */
function Viewer({ designs, index, canEdit, onIndex, onClose, onChange, onDelete }: {
  designs: Design[]; index: number; canEdit: boolean; onIndex: (i: number) => void; onClose: () => void; onChange: (d: Design) => void; onDelete: (d: Design) => void;
}) {
  const d = designs[index];
  const [note, setNote] = useState(d.data.note ?? '');
  useEffect(() => setNote(d.data.note ?? ''), [d.key, d.data.note]);
  useEffect(() => {
    const key = (e: KeyboardEvent) => {
      if ((e.target as HTMLElement)?.tagName === 'TEXTAREA') return;
      if (e.key === 'Escape') onClose();
      else if (e.key === 'ArrowRight') onIndex(Math.min(designs.length - 1, index + 1));
      else if (e.key === 'ArrowLeft') onIndex(Math.max(0, index - 1));
    };
    window.addEventListener('keydown', key); return () => window.removeEventListener('keydown', key);
  }, [index, designs.length, onClose, onIndex]);
  const size = SIZE[d.data.device] ?? SIZE.phone;
  const width = Math.min(size.w, d.data.device === 'phone' ? 380 : Math.max(480, window.innerWidth - 520));
  return createPortal(
    <div className="dz-view" role="dialog" aria-modal="true" aria-label={d.title}>
      <div className="dz-stage">
        <button type="button" className="dz-nav l" aria-label="Previous design" disabled={index === 0} onClick={() => onIndex(index - 1)}><Icon name="chevronL" size={18} /></button>
        <div key={d.key} className="dz-rise"><Screen d={d.data} width={width} live /></div>
        <button type="button" className="dz-nav r" aria-label="Next design" disabled={index >= designs.length - 1} onClick={() => onIndex(index + 1)}><Icon name="chevronR" size={18} /></button>
      </div>
      <aside className="dz-side">
        <button type="button" className="dz-close" onClick={onClose} autoFocus>Esc · Close</button>
        <p className="dx-eyebrow">{d.data.source === 'figma' ? 'Figma' : d.data.source === 'ai' ? 'AI draft' : 'Picture'} · {size.label} · {index + 1} of {designs.length}</p>
        <h2>{d.title}</h2>
        {d.data.group && <p className="dz-muted">Flow: {d.data.group}</p>}
        <div className="dz-states" role="group" aria-label="State">
          {(Object.keys(STATE) as DesignData['state'][]).map((s) => <button key={s} type="button" disabled={!canEdit} aria-pressed={d.data.state === s} className={`dz-state s-${s}${d.data.state === s ? ' on' : ''}`} onClick={() => onChange({ ...d, data: { ...d.data, state: s } })}>{STATE[s]}</button>)}
        </div>
        {d.data.prompt && <p className="dz-muted">Asked for: “{d.data.prompt}”</p>}
        <label className="dz-note">Note<textarea rows={4} value={note} disabled={!canEdit} maxLength={1000} onChange={(e) => setNote(e.target.value)} placeholder="What to build, what is still open, who signed it off…" /></label>
        {canEdit && note !== (d.data.note ?? '') && <button type="button" className="dx-btn pri sm" onClick={() => onChange({ ...d, data: { ...d.data, note: note.trim() || undefined } })}>Save note</button>}
        <div className="dz-actions">
          {d.data.source === 'figma' && d.data.url && <a className="dx-btn" href={d.data.url} target="_blank" rel="noreferrer noopener">Open in Figma</a>}
          {canEdit && <button type="button" className="dx-btn" onClick={() => onDelete(d)}>Remove</button>}
        </div>
      </aside>
    </div>, document.body);
}
